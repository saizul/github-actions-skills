#!/usr/bin/env python3
"""Detect package ecosystems in a repository and generate .github/dependabot.yml.

Detects github-actions, npm, bun, pip, uv, gomod, cargo, bundler, composer, maven,
gradle, nuget, docker, docker-compose, terraform, mix, pub, swift, helm, elm,
devcontainers and gitsubmodule from manifest/lock files, and writes one update block per
ecosystem (with `directories` when there are several), weekly schedule, grouped
minor/patch updates and commit-message prefixes. Prints to stdout by default.

--check FILE compares an existing dependabot.yml with what was detected and exits 1 when
an ecosystem is missing (useful in CI). No network access; reads file names only.

Exit codes: 0 = ok, 1 = --check found missing ecosystems, 2 = error.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "vendor", "dist", "build", "target", ".tox", "__pycache__"}
# ecosystem -> file name patterns (glob, matched against the file name)
MARKERS = {
    "npm": ["package-lock.json", "yarn.lock", "pnpm-lock.yaml", "npm-shrinkwrap.json"],
    "bun": ["bun.lock", "bun.lockb"],
    "uv": ["uv.lock"],
    "pip": ["requirements*.txt", "Pipfile", "Pipfile.lock", "poetry.lock", "setup.py", "setup.cfg", "pyproject.toml"],
    "gomod": ["go.mod"],
    "cargo": ["Cargo.toml"],
    "bundler": ["Gemfile"],
    "composer": ["composer.json"],
    "maven": ["pom.xml"],
    "gradle": ["build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"],
    "nuget": ["*.csproj", "*.fsproj", "*.vbproj", "packages.config", "Directory.Packages.props"],
    "docker": ["Dockerfile", "Dockerfile.*", "*.Dockerfile", "Containerfile"],
    "docker-compose": ["docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml"],
    "terraform": ["*.tf"],
    "mix": ["mix.exs"],
    "pub": ["pubspec.yaml"],
    "swift": ["Package.swift"],
    "helm": ["Chart.yaml"],
    "elm": ["elm.json"],
}
ORDER = ["github-actions", *MARKERS, "devcontainers", "gitsubmodule"]


def match(name: str, pattern: str) -> bool:
    regex = "^" + re.escape(pattern).replace(r"\*", ".*") + "$"
    return re.match(regex, name) is not None


def detect(root: Path) -> dict[str, list[str]]:
    found: dict[str, set[str]] = {}

    def add(eco: str, directory: str) -> None:
        found.setdefault(eco, set()).add(directory)

    if (root / ".github" / "workflows").is_dir() or (root / "action.yml").is_file() or (root / "action.yaml").is_file():
        add("github-actions", "/")
    if (root / ".devcontainer.json").is_file() or (root / ".devcontainer").is_dir():
        add("devcontainers", "/")
    if (root / ".gitmodules").is_file():
        add("gitsubmodule", "/")
    package_json_dirs = set()
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]) or not path.is_file():
            continue
        directory = "/" + "/".join(rel.parts[:-1]) if len(rel.parts) > 1 else "/"
        name = path.name
        if name == "package.json":
            package_json_dirs.add(directory)
        for eco, patterns in MARKERS.items():
            if any(match(name, pat) for pat in patterns):
                add(eco, directory)
    # uv projects: pyproject/requirements next to uv.lock belong to uv, not pip
    for d in found.get("uv", set()):
        found.get("pip", set()).discard(d)
    for d in found.get("bun", set()):
        found.get("npm", set()).discard(d)
    # package.json without a lockfile still means npm (yarn/pnpm workspaces use the root)
    if not found.get("npm") and not found.get("bun") and package_json_dirs:
        add("npm", min(package_json_dirs, key=len))
    return {eco: sorted(dirs) for eco, dirs in found.items() if dirs}


def render(
    ecosystems: dict[str, list[str]],
    interval: str = "weekly",
    group: bool = True,
    limit: int | None = None,
    cooldown: int | None = None,
    labels: list[str] | None = None,
) -> str:
    out = [
        "# Generated by dependabot_gen.py - review before committing.",
        "# Options: https://docs.github.com/en/code-security/reference/supply-chain-security/dependabot-options-reference",
        "version: 2",
        "updates:",
    ]
    for eco in ORDER:
        dirs = ecosystems.get(eco)
        if not dirs:
            continue
        out.append(f'  - package-ecosystem: "{eco}"')
        if len(dirs) == 1:
            out.append(f'    directory: "{dirs[0]}"')
        else:
            out.append("    directories:")
            out += [f'      - "{d}"' for d in dirs]
        out.append("    schedule:")
        out.append(f'      interval: "{interval}"')
        prefix = "ci" if eco == "github-actions" else "deps"
        out.append("    commit-message:")
        out.append(f'      prefix: "{prefix}"')
        if labels:
            out.append("    labels:")
            out += [f'      - "{lab}"' for lab in labels]
        if limit is not None:
            out.append(f"    open-pull-requests-limit: {limit}")
        if cooldown is not None:
            out.append("    cooldown:")
            out.append(f"      default-days: {cooldown}")
        if group and eco != "gitsubmodule":
            name = "actions" if eco == "github-actions" else f"{eco.replace('-', '_')}-minor-patch"
            out.append("    groups:")
            out.append(f"      {name}:")
            if eco == "github-actions":
                out.append('        patterns: ["*"]')
            else:
                out.append('        update-types: ["minor", "patch"]')
    return "\n".join(out) + "\n"


def existing_ecosystems(text: str) -> set[str]:
    return set(re.findall(r"package-ecosystem:\s*[\"']?([A-Za-z0-9_-]+)", text))


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Detect ecosystems and generate .github/dependabot.yml.")
    p.add_argument("root", nargs="?", default=".", type=Path, help="repository root (default .)")
    p.add_argument("--interval", default="weekly", choices=["daily", "weekly", "monthly"], help="schedule interval")
    p.add_argument("--no-groups", action="store_true", help="one pull request per dependency")
    p.add_argument("--limit", type=int, help="open-pull-requests-limit per ecosystem")
    p.add_argument("--cooldown", type=int, help="cooldown default-days (delay brand-new versions)")
    p.add_argument("--label", action="append", default=[], help="label for Dependabot PRs (repeatable)")
    p.add_argument("--output", type=Path, help="write to this file instead of stdout")
    p.add_argument("--force", action="store_true", help="overwrite --output if it exists")
    p.add_argument("--check", type=Path, help="existing dependabot.yml to compare; exit 1 if ecosystems are missing")
    p.add_argument("--json", action="store_true", help="print detected ecosystems as JSON")
    args = p.parse_args(argv)
    if not args.root.is_dir():
        print(f"error: {args.root} is not a directory", file=sys.stderr)
        return 2
    eco = detect(args.root)
    if args.check:
        try:
            have = existing_ecosystems(args.check.read_text(encoding="utf-8"))
        except OSError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        missing = sorted(set(eco) - have)
        extra = sorted(have - set(eco))
        if args.json:
            print(
                json.dumps({"detected": eco, "configured": sorted(have), "missing": missing, "extra": extra}, indent=2)
            )
        else:
            for m in missing:
                print(f"MISSING {m}: {', '.join(eco[m])}")
            for x in extra:
                print(f"EXTRA   {x}: configured but no manifest found (stale?)")
            print(f"{len(have)} configured, {len(eco)} detected, {len(missing)} missing")
        return 1 if missing else 0
    if args.json:
        print(json.dumps(eco, indent=2))
        return 0
    if not eco:
        print("error: no supported manifests found", file=sys.stderr)
        return 2
    text = render(eco, args.interval, not args.no_groups, args.limit, args.cooldown, args.label)
    if args.output:
        if args.output.exists() and not args.force:
            print(f"error: {args.output} exists; use --force or --check", file=sys.stderr)
            return 2
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"wrote {args.output} ({len(eco)} ecosystems)")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
